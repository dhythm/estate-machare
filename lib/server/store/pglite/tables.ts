export const listingTable: TableSpec<Listing> = {
  table: 'listings',
  columns: [
    'id',
    'property',
    'name',
    'category',
    'maker',
    'year',
    'hours',
    'condition',
    'prefecture',
    'city',
    'image',
    'images',
    'summary',
    'deals',
    'sale_price',
    'rent_per_day',
    'rent_to_own',
    'rent_to_own_credit_rate',
    'rent_to_own_credit_cap',
    'seller_name',
    'seller_kind',
    'seller_rating',
    'seller_reviews',
    'tags',
    'owner_user_id',
    'created_at',
    'updated_at',
    'moderation_status',
    'moderation_note',
    'moderated_at',
    'withdrawn_at',
  ],
  toRow: (listing) => [
    listing.id,
    nullable(listing.property),
    listing.name,
    listing.category,
    listing.maker,
    listing.year,
    listing.hours,
    listing.condition,
    listing.prefecture,
    listing.city,
    listing.image,
    nullable(listing.images),
    listing.summary,
    listing.deals,
    nullable(listing.salePrice),
    nullable(listing.rentPerDay),
    nullable(listing.rentToOwn),
    nullable(listing.rentToOwnCreditRate),
    nullable(listing.rentToOwnCreditCap),
    listing.seller.name,
    listing.seller.kind,
    listing.seller.rating,
    listing.seller.reviews,
    listing.tags,
    nullable(listing.ownerUserId),
    nullable(listing.createdAt),
    nullable(listing.updatedAt),
    nullable(listing.moderationStatus),
    nullable(listing.moderationNote),
    nullable(listing.moderatedAt),
    nullable(listing.withdrawnAt),
  ],
  fromRow: (row: Row) =>
    compact({
      id: row.id as string,
      property: (row.property as Listing['property']) ?? undefined,
      name: row.name as string,
      category: row.category as string,
      maker: row.maker as string,
      year: row.year as number,
      hours: row.hours as number,
      condition: row.condition as Listing['condition'],
      prefecture: row.prefecture as string,
      city: row.city as string,
      image: row.image as string,
      images: (row.images as string[] | null) ?? undefined,
      summary: row.summary as string,
      deals: row.deals as Listing['deals'],
      salePrice: (row.sale_price as number | null) ?? undefined,
      rentPerDay: (row.rent_per_day as number | null) ?? undefined,
      rentToOwn: (row.rent_to_own as boolean | null) ?? undefined,
      rentToOwnCreditRate:
        (row.rent_to_own_credit_rate as number | null) ?? undefined,
      rentToOwnCreditCap:
        (row.rent_to_own_credit_cap as number | null) ?? undefined,
      seller: {
        name: row.seller_name as string,
        kind: row.seller_kind as Listing['seller']['kind'],
        rating: row.seller_rating as number,
        reviews: row.seller_reviews as number,
      },
      tags: row.tags as string[],
      ownerUserId: (row.owner_user_id as string | null) ?? undefined,
      createdAt: isoString(row.created_at),
      updatedAt: isoString(row.updated_at),
      moderationStatus:
        (row.moderation_status as Listing['moderationStatus'] | null) ??
        undefined,
      moderationNote: (row.moderation_note as string | null) ?? undefined,
      moderatedAt: isoString(row.moderated_at),
      withdrawnAt: isoString(row.withdrawn_at),
    }),
}

