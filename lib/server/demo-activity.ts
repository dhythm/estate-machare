function lease(
  input: Omit<
    Lease,
    | 'months'
    | 'rentTotal'
    | 'deposit'
    | 'keyMoney'
    | 'initialCost'
    | 'createdAt'
    | 'updatedAt'
  > & {
    depositMonths?: number
    keyMoneyMonths?: number
    createdAt: string
    updatedAt: string
  },
): Lease {
  const { depositMonths, keyMoneyMonths, ...rest } = input
  const months = countLeaseMonths(input.startDate, input.endDate)
  const cost = calculateInitialCost({
    rentPerMonth: input.rentPerMonth,
    depositMonths,
    keyMoneyMonths,
  })
  return {
    ...rest,
    months,
    rentTotal: months * input.rentPerMonth,
    deposit: cost.deposit,
    keyMoney: cost.keyMoney,
    initialCost: cost.total,
  }
}

